// جدولِ تاریخ‌های نزدیک تا مدل «فردا» و «سه‌شنبهٔ آینده» را بی‌خطا حساب کند
const WEEKDAYS_FA = ['یکشنبه', 'دوشنبه', 'سه‌شنبه', 'چهارشنبه', 'پنجشنبه', 'جمعه', 'شنبه'];
function dateContext() {
  const fmt = (o) => {
    const j = tehranTodayJalali(o);
    const d = new Date(Date.now() + o * 86400000);
    const wd = new Intl.DateTimeFormat('en-US', { timeZone: 'Asia/Tehran', weekday: 'short' }).format(d);
    const name = WEEKDAYS_FA[['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'].indexOf(wd)];
    return `${j.jy}/${String(j.jm).padStart(2, '0')}/${String(j.jd).padStart(2, '0')} ${name}`;
  };
  const now = new Intl.DateTimeFormat('en-GB', { timeZone: 'Asia/Tehran', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).format(new Date());
  const rows = [];
  for (let o = -3; o <= 14; o++) rows.push(`${o === 0 ? '◀ امروز ' : o === 1 ? 'فردا ' : o === -1 ? 'دیروز ' : ''}${fmt(o)}`);
  return `اکنون: ${fmt(0)} ساعت ${now} (تهران).\nتاریخ‌های نزدیک:\n${rows.join('\n')}`;
}

// وضعیتِ همین کاربر — تا پاسخ‌ها به وضعیت واقعی او مربوط باشد.
// عمداً فقط شمارش‌ها فرستاده می‌شود، نه محتوای کارها و پیام‌ها.
function userContext(user) {
  const c = db.prepare(`
    SELECT
      (SELECT COUNT(*) FROM tasks WHERE assignee_id = @uid AND status != 'done') AS open_tasks,
      (SELECT COUNT(*) FROM tasks WHERE assignee_id = @uid AND status != 'done'
         AND deadline IS NOT NULL AND datetime(deadline) < datetime('now')) AS overdue_tasks,
      (SELECT COUNT(*) FROM workflow_requests WHERE requester_id = @uid AND status IN ('in_progress','awaiting_requester')) AS open_requests
  `).get({ uid: user.id });
  const dept = user.department_id
    ? db.prepare('SELECT name FROM departments WHERE id = ?').get(user.department_id)?.name : null;
  const roleFa = user.role === 'admin' ? 'مدیر سامانه' : user.role === 'manager' ? 'سرگروه/مدیر واحد' : 'کارمند';
  return `کاربرِ پرسنده: ${user.full_name} — نقش: ${roleFa}${dept ? ` — واحد: ${dept}` : ''}.
وضعیت فعلی او: ${c.open_tasks} وظیفهٔ باز (${c.overdue_tasks} تای آن دارای تأخیر)، ${c.open_requests} درخواستِ در جریان در کارتابل.`;
}

// پیام سیستمیِ کامل برای یک کاربر مشخص
export function systemPrompt(user, { withContext = true } = {}) {
  return [withContext ? dateContext() : '', RULES, SYSTEM_MAP, withContext ? userContext(user) : '']
    .filter(Boolean).join('\n\n');
}

